//! `vex init --agent claude|codex`: wire an agent harness to `vex mcp`.
//!
//! Everything is written inside the project and names bare `vex`, never an
//! absolute launcher path. vex owns only its own pieces: the `vex` entry in
//! `.mcp.json` (Claude Code), a fenced `[mcp_servers.vex]` block in
//! `.codex/config.toml` (Codex), and the vex-code-context skill directory.
//! Other servers keep their exact JSON text, other TOML is untouched, and a
//! re-run changes nothing that is already right.

use indexmap::IndexMap;
use serde::Serialize;
use serde_json::value::RawValue;
use std::path::{Path, PathBuf};

/// A harness vex can configure.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Agent {
    Claude,
    Codex,
}

impl Agent {
    pub fn name(self) -> &'static str {
        match self {
            Agent::Claude => "claude",
            Agent::Codex => "codex",
        }
    }

    /// `claude`, `codex`, or `all` (both).
    pub fn parse(name: &str) -> Option<Vec<Agent>> {
        match name {
            "claude" => Some(vec![Agent::Claude]),
            "codex" => Some(vec![Agent::Codex]),
            "all" => Some(vec![Agent::Claude, Agent::Codex]),
            _ => None,
        }
    }

    /// Where this harness discovers project skills.
    fn skills_dir(self) -> &'static str {
        match self {
            Agent::Claude => ".claude/skills",
            Agent::Codex => ".agents/skills",
        }
    }
}

/// What `install` did for one harness.
#[derive(Debug, Clone, Serialize)]
pub struct AgentReport {
    pub agent: &'static str,
    pub config: PathBuf,
    /// `added`, `updated`, `unchanged`, or `kept` (a hand-written entry vex
    /// leaves alone).
    pub config_action: &'static str,
    pub skill: PathBuf,
    /// `added`, `updated`, `unchanged`, or `kept` (a skill vex did not write).
    pub skill_action: &'static str,
}

/// Why a harness could not be configured.
#[derive(Debug)]
pub enum AgentError {
    /// The existing config cannot be edited safely; it was left as it was.
    Unparseable { path: PathBuf, reason: String },
    Io {
        path: PathBuf,
        error: std::io::Error,
    },
}

impl std::fmt::Display for AgentError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            AgentError::Unparseable { path, reason } => write!(
                f,
                "{}: {reason}; left unchanged, fix it and re-run",
                path.display()
            ),
            AgentError::Io { path, error } => write!(f, "{}: {error}", path.display()),
        }
    }
}

const SERVER: &str = "vex";
const SKILL: &str = "vex-code-context";
/// Marks a skill file vex wrote, so a re-run may replace it.
const SKILL_MARKER: &str = "<!-- generated by vex init";
/// The skill bundle: path inside the skill directory, contents.
const SKILL_FILES: &[(&str, &str)] = &[
    (
        "SKILL.md",
        include_str!("../../../resources/vex-code-context/SKILL.md"),
    ),
    (
        "references/change-safety.md",
        include_str!("../../../resources/vex-code-context/references/change-safety.md"),
    ),
    (
        "references/freshness.md",
        include_str!("../../../resources/vex-code-context/references/freshness.md"),
    ),
    (
        "references/host-setup.md",
        include_str!("../../../resources/vex-code-context/references/host-setup.md"),
    ),
    (
        "references/reading-results.md",
        include_str!("../../../resources/vex-code-context/references/reading-results.md"),
    ),
];
const TOML_START: &str =
    "# >>> vex: generated by `vex init --agent codex`; edits inside this block are replaced";
const TOML_END: &str = "# <<< vex";

/// The skill bundle vex installs: relative path and contents.
pub fn skill_files() -> &'static [(&'static str, &'static str)] {
    SKILL_FILES
}

/// The harnesses already wired to `vex mcp` in the project at `root`.
pub fn configured(root: &Path) -> Vec<Agent> {
    let mut wired = Vec::new();
    let claude = std::fs::read_to_string(root.join(".mcp.json"))
        .ok()
        .and_then(|t| serde_json::from_str::<serde_json::Value>(&t).ok())
        .is_some_and(|v| v["mcpServers"][SERVER].is_object());
    if claude {
        wired.push(Agent::Claude);
    }
    let codex = std::fs::read_to_string(root.join(".codex/config.toml"))
        .ok()
        .and_then(|t| t.parse::<toml::Table>().ok())
        .is_some_and(|t| t.get("mcp_servers").and_then(|m| m.get(SERVER)).is_some());
    if codex {
        wired.push(Agent::Codex);
    }
    wired
}

/// Configure `agent` for the project at `root`.
pub fn install(root: &Path, agent: Agent) -> Result<AgentReport, AgentError> {
    let (config, config_action) = match agent {
        Agent::Claude => claude(root)?,
        Agent::Codex => codex(root)?,
    };
    let skill = root.join(agent.skills_dir()).join(SKILL);
    let skill_action = install_skill(&skill)?;
    Ok(AgentReport {
        agent: agent.name(),
        config,
        config_action,
        skill,
        skill_action,
    })
}

fn io(path: &Path) -> impl FnOnce(std::io::Error) -> AgentError + '_ {
    move |error| AgentError::Io {
        path: path.to_path_buf(),
        error,
    }
}

/// Write `text` to `path` through a temporary file and a rename.
fn write_atomic(path: &Path, text: &str) -> Result<(), AgentError> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(io(parent))?;
    }
    let tmp = path.with_extension(format!("vex-tmp-{}", std::process::id()));
    std::fs::write(&tmp, text).map_err(io(&tmp))?;
    std::fs::rename(&tmp, path).map_err(io(path))
}

/// The `vex` server entry as written, `command` first.
const CLAUDE_ENTRY_TEXT: &str = "{\n  \"command\": \"vex\",\n  \"args\": [\n    \"mcp\"\n  ]\n}";

/// The `vex` server entry, as `.mcp.json` holds it.
fn claude_entry() -> serde_json::Value {
    serde_json::from_str(CLAUDE_ENTRY_TEXT).expect("entry parses")
}

/// Indent every line after the first by `pad`.
fn indent(text: &str, pad: &str) -> String {
    text.lines().collect::<Vec<_>>().join(&format!("\n{pad}"))
}

/// `.mcp.json`: add or update the `vex` server, keeping every other key and
/// server as its exact original JSON text.
fn claude(root: &Path) -> Result<(PathBuf, &'static str), AgentError> {
    let path = root.join(".mcp.json");
    let existing = match std::fs::read_to_string(&path) {
        Ok(text) => Some(text),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => None,
        Err(e) => return Err(io(&path)(e)),
    };
    let unparseable = |reason: String| AgentError::Unparseable {
        path: path.clone(),
        reason,
    };
    let mut top: IndexMap<String, Box<RawValue>> = match &existing {
        None => IndexMap::new(),
        Some(text) => serde_json::from_str(text)
            .map_err(|e| unparseable(format!("not a JSON object ({e})")))?,
    };
    let mut servers: IndexMap<String, Box<RawValue>> = match top.get("mcpServers") {
        None => IndexMap::new(),
        Some(raw) => serde_json::from_str(raw.get())
            .map_err(|e| unparseable(format!("mcpServers is not an object ({e})")))?,
    };
    let entry = claude_entry();
    let action = match servers.get(SERVER) {
        Some(raw) => {
            let current: serde_json::Value = serde_json::from_str(raw.get())
                .map_err(|e| unparseable(format!("unreadable vex entry ({e})")))?;
            if current == entry {
                return Ok((path, "unchanged"));
            }
            "updated"
        }
        None => "added",
    };
    servers.insert(
        SERVER.to_string(),
        RawValue::from_string(indent(CLAUDE_ENTRY_TEXT, "    ")).expect("valid JSON"),
    );
    let mut lines = Vec::new();
    for (name, raw) in &servers {
        lines.push(format!("    {}: {}", json_string(name), raw.get()));
    }
    let servers_text = format!("{{\n{}\n  }}", lines.join(",\n"));
    top.insert(
        "mcpServers".to_string(),
        RawValue::from_string(servers_text).expect("valid JSON"),
    );
    let mut lines = Vec::new();
    for (key, raw) in &top {
        lines.push(format!("  {}: {}", json_string(key), raw.get()));
    }
    let text = format!("{{\n{}\n}}\n", lines.join(",\n"));
    debug_assert!(serde_json::from_str::<serde_json::Value>(&text).is_ok());
    write_atomic(&path, &text)?;
    Ok((path, action))
}

fn json_string(s: &str) -> String {
    serde_json::to_string(s).expect("strings serialise")
}

/// The fenced `[mcp_servers.vex]` block for Codex.
fn codex_block() -> String {
    format!("{TOML_START}\n[mcp_servers.vex]\ncommand = \"vex\"\nargs = [\"mcp\"]\n{TOML_END}\n")
}

/// `.codex/config.toml`: add or refresh vex's fenced block; a `vex` server
/// written by hand outside the fence is kept as it is.
fn codex(root: &Path) -> Result<(PathBuf, &'static str), AgentError> {
    let path = root.join(".codex/config.toml");
    let existing = match std::fs::read_to_string(&path) {
        Ok(text) => text,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => String::new(),
        Err(e) => return Err(io(&path)(e)),
    };
    let block = codex_block();
    let fenced = existing.find(TOML_START).and_then(|start| {
        existing[start..]
            .find(TOML_END)
            .map(|end| (start, start + end + TOML_END.len()))
    });
    let outside = match fenced {
        Some((start, end)) => format!("{}{}", &existing[..start], &existing[end..]),
        None => existing.clone(),
    };
    let table: toml::Table =
        outside
            .parse()
            .map_err(|e: toml::de::Error| AgentError::Unparseable {
                path: path.clone(),
                reason: format!("not valid TOML ({})", e.message()),
            })?;
    let by_hand = table
        .get("mcp_servers")
        .and_then(|s| s.as_table())
        .is_some_and(|s| s.contains_key(SERVER));
    if by_hand {
        return Ok((path, "kept"));
    }
    let (text, action) = match fenced {
        Some((start, end)) => {
            let mut rest = &existing[end..];
            rest = rest.strip_prefix('\n').unwrap_or(rest);
            let text = format!("{}{block}{rest}", &existing[..start]);
            let action = if text == existing {
                "unchanged"
            } else {
                "updated"
            };
            (text, action)
        }
        None if existing.trim().is_empty() => (block, "added"),
        None => {
            let sep = if existing.ends_with('\n') {
                "\n"
            } else {
                "\n\n"
            };
            (format!("{existing}{sep}{block}"), "added")
        }
    };
    if action != "unchanged" {
        write_atomic(&path, &text)?;
    }
    Ok((path, action))
}

/// Write the skill bundle into `dir`, unless its SKILL.md is one vex did not
/// write.
fn install_skill(dir: &Path) -> Result<&'static str, AgentError> {
    let skill_md = dir.join("SKILL.md");
    let current = std::fs::read_to_string(&skill_md).ok();
    if current
        .as_deref()
        .is_some_and(|t| !t.contains(SKILL_MARKER))
    {
        return Ok("kept");
    }
    let mut changed = false;
    for (rel, body) in SKILL_FILES {
        let path = dir.join(rel);
        if std::fs::read_to_string(&path).ok().as_deref() != Some(*body) {
            write_atomic(&path, body)?;
            changed = true;
        }
    }
    Ok(match (current, changed) {
        (None, _) => "added",
        (Some(_), true) => "updated",
        (Some(_), false) => "unchanged",
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    fn scratch(tag: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("vex-agent-{tag}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn configured_sees_what_install_wrote() {
        let root = scratch("installed");
        assert!(configured(&root).is_empty());
        install(&root, Agent::Codex).unwrap();
        assert_eq!(configured(&root), vec![Agent::Codex]);
        install(&root, Agent::Claude).unwrap();
        assert_eq!(configured(&root), vec![Agent::Claude, Agent::Codex]);
        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn configured_ignores_other_servers_and_unreadable_files() {
        let root = scratch("others");
        std::fs::write(
            root.join(".mcp.json"),
            r#"{"mcpServers": {"cortex": {"command": "cortex-mcp"}}}"#,
        )
        .unwrap();
        std::fs::create_dir_all(root.join(".codex")).unwrap();
        std::fs::write(root.join(".codex/config.toml"), "not = [valid toml").unwrap();
        assert!(configured(&root).is_empty());
        // A vex server written by hand counts as wired.
        std::fs::write(
            root.join(".codex/config.toml"),
            "[mcp_servers.vex]\ncommand = \"vex\"\n",
        )
        .unwrap();
        assert_eq!(configured(&root), vec![Agent::Codex]);
        let _ = std::fs::remove_dir_all(&root);
    }
}
