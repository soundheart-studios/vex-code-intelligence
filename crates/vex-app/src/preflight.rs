//! Preflight: estimate index cost before the slow embed phase and suggest
//! exclusions for low-value, high-cost content. A port of Cortex's
//! `indexer/preflight.py` `scan`.
//!
//! "AST-parsable" means a grammar compiled into THIS binary, so estimates
//! for languages vex has not wired yet (P8) differ from Cortex's.

use crate::walk::walk;
use std::collections::{BTreeMap, BTreeSet, HashSet};
use std::io::Read;
use std::path::{Path, PathBuf};
use vex_extract::language::{HEAD_BYTES, language_of};
use vex_extract::text::path_suffix;

const GENERATED_MARKERS: &[&[u8]] = &[
    b"do not edit",
    b"@generated",
    b"auto-generated",
    b"autogenerated",
    b"code generated by",
    b"automatically generated",
    b"generated by tree-sitter",
    b"#include \"tree_sitter/parser.h\"",
];
/// Extensions that hold records rather than code.
const DATA_EXTS: &[&str] = &[
    ".json", ".jsonl", ".ndjson", ".csv", ".tsv", ".yaml", ".yml",
];
/// Meaningful configuration files in those formats, never bulk data.
const CONFIG_NAMES: &[&str] = &[
    "package.json",
    "package-lock.json",
    "tsconfig.json",
    "jsconfig.json",
    "composer.json",
    "deno.json",
    "deno.jsonc",
    "angular.json",
    "nx.json",
    "turbo.json",
    "vercel.json",
    "now.json",
    "manifest.json",
    "bower.json",
    "lerna.json",
    "pnpm-workspace.yaml",
    "docker-compose.yml",
    "docker-compose.yaml",
    "pubspec.yaml",
    "serverless.yml",
    ".eslintrc.json",
    "renovate.json",
    "cargo.toml",
    "openapi.json",
    "swagger.json",
];
const BULK_DATA_BYTES: u64 = 32 * 1024;
const BYTES_PER_LINE: u64 = 35;
const SUGGEST_MIN_CHUNKS: u64 = 300;
const SUGGEST_FALLBACK_RATIO: f64 = 0.7;
const SUGGEST_GENERATED_RATIO: f64 = 0.5;
const SUGGEST_DATA_RATIO: f64 = 0.5;

#[derive(Debug, Clone, Default, PartialEq)]
pub struct DirStat {
    pub files: u64,
    pub est_chunks: u64,
    pub fallback_chunks: u64,
    pub generated_files: u64,
    pub generated_chunks: u64,
    pub data_files: u64,
    pub data_chunks: u64,
    pub languages: BTreeSet<String>,
}

#[derive(Debug, Clone, PartialEq)]
pub struct Report {
    pub dirs: BTreeMap<String, DirStat>,
    pub total_files: u64,
    pub total_est_chunks: u64,
    /// Ignore patterns, sorted.
    pub suggestions: Vec<String>,
    pub suggested_savings: u64,
    /// Tool caches the walker skipped, sorted.
    pub ignored_caches: Vec<String>,
}

fn head(path: &Path, n: usize) -> Option<Vec<u8>> {
    let mut buf = Vec::new();
    std::fs::File::open(path)
        .ok()?
        .take(n as u64)
        .read_to_end(&mut buf)
        .ok()?;
    Some(buf)
}

fn is_generated(path: &Path) -> bool {
    let Some(h) = head(path, 2048) else {
        return false;
    };
    let lower = h.to_ascii_lowercase();
    GENERATED_MARKERS
        .iter()
        .any(|m| lower.windows(m.len()).any(|w| w == *m))
}

fn is_bulk_data(name: &str, size: u64) -> bool {
    let suffix = path_suffix(name).to_lowercase();
    DATA_EXTS.contains(&suffix.as_str())
        && !CONFIG_NAMES.contains(&name.to_lowercase().as_str())
        && size >= BULK_DATA_BYTES
}

fn parts(rel: &str) -> Vec<&str> {
    rel.split('/').filter(|p| !p.is_empty()).collect()
}

/// Group by one or two leading components (`internal/cbm`, not `internal`).
fn group(rel: &str) -> String {
    let p = parts(rel);
    if p.len() == 1 {
        return "(root)".into();
    }
    if p.len() > 2 && ["src", "internal", "packages", "apps", "lib", "pkg"].contains(&p[0]) {
        return format!("{}/{}", p[0], p[1]);
    }
    p[0].to_string()
}

/// Directories under `root` that are repositories in their own right: a
/// `.git` DIRECTORY (an independent clone), checked on every ancestor of a
/// scanned file. A `.git` FILE (a submodule) is part of the checkout.
pub fn nested_repos(root: &Path, scanned: &HashSet<PathBuf>) -> Vec<String> {
    let mut candidates: BTreeSet<Vec<String>> = BTreeSet::new();
    for dir in scanned {
        let mut current = dir.clone();
        loop {
            if let Ok(rel) = current.strip_prefix(root) {
                candidates.insert(
                    rel.components()
                        .map(|c| c.as_os_str().to_string_lossy().into_owned())
                        .collect(),
                );
            }
            if current == root || current.parent().is_none() {
                break;
            }
            current = current.parent().unwrap().to_path_buf();
        }
    }
    let mut found: Vec<String> = Vec::new();
    for rel_parts in candidates {
        if rel_parts.is_empty() {
            continue;
        }
        let rel = rel_parts.join("/");
        if root.join(&rel).join(".git").is_dir() {
            found.push(rel);
        }
    }
    found
        .iter()
        .filter(|d| {
            !found
                .iter()
                .any(|o| o != *d && d.starts_with(&format!("{o}/")))
        })
        .cloned()
        .collect()
}

/// Cortex `preflight.scan`. `already_indexed` holds relative paths whose
/// cost is zero because incremental sync will skip them.
pub fn scan(root: &Path, already_indexed: &HashSet<String>) -> Report {
    let walked = walk(root);
    let mut scanned_dirs: HashSet<PathBuf> = HashSet::new();
    let mut dirs: BTreeMap<String, DirStat> = BTreeMap::new();
    // Insertion order kept for the suggestion pass, as Python's dict does.
    let mut subs: Vec<(String, DirStat)> = Vec::new();
    let mut total = 0u64;
    for p in &walked.files {
        let rel = p
            .strip_prefix(root)
            .unwrap_or(p)
            .to_string_lossy()
            .into_owned();
        if let Some(parent) = p.parent() {
            scanned_dirs.insert(parent.to_path_buf());
        }
        if already_indexed.contains(&rel) {
            continue;
        }
        let name = p
            .file_name()
            .map(|n| n.to_string_lossy().into_owned())
            .unwrap_or_default();
        let lang = language_of(&name, head(p, HEAD_BYTES).as_deref());
        let ast_ok = !lang.is_empty() && vex_extract::language(lang).is_some();
        let Ok(meta) = std::fs::metadata(p) else {
            continue;
        };
        let size = meta.len();
        let est_lines = (size / BYTES_PER_LINE).max(1);
        let est = est_lines / if ast_ok { 70 } else { 55 } + 1;
        let generated = is_generated(p);
        let bulk = is_bulk_data(&name, size);
        let rel_parts = parts(&rel);
        let sub_key = {
            let dir_parts = &rel_parts[..rel_parts.len().saturating_sub(1)];
            let joined = dir_parts
                .iter()
                .take(3)
                .copied()
                .collect::<Vec<_>>()
                .join("/");
            if joined.is_empty() {
                "(root)".to_string()
            } else {
                joined
            }
        };
        let language_label = if lang.is_empty() {
            path_suffix(&rel).to_string()
        } else {
            lang.to_string()
        };
        let sub_index = match subs.iter().position(|(k, _)| *k == sub_key) {
            Some(i) => i,
            None => {
                subs.push((sub_key, DirStat::default()));
                subs.len() - 1
            }
        };
        for d in [dirs.entry(group(&rel)).or_default(), &mut subs[sub_index].1] {
            d.files += 1;
            d.est_chunks += est;
            d.languages.insert(language_label.clone());
            if !ast_ok {
                d.fallback_chunks += est;
            }
            if generated {
                d.generated_files += 1;
                d.generated_chunks += est;
            }
            if bulk {
                d.data_files += 1;
                d.data_chunks += est;
            }
        }
        total += est;
    }

    let mut suggestions: Vec<String> = Vec::new();
    let mut savings = 0u64;
    for (name, d) in &subs {
        if name == "(root)" || d.est_chunks < SUGGEST_MIN_CHUNKS {
            continue;
        }
        let ratio = |part: u64| part as f64 / d.est_chunks as f64;
        if ratio(d.fallback_chunks) > SUGGEST_FALLBACK_RATIO
            || ratio(d.generated_chunks) > SUGGEST_GENERATED_RATIO
            || ratio(d.data_chunks) > SUGGEST_DATA_RATIO
        {
            suggestions.push(name.clone());
            savings += d.est_chunks;
        }
    }
    for repo in nested_repos(root, &scanned_dirs) {
        if !suggestions.contains(&repo) {
            savings += subs
                .iter()
                .filter(|(n, _)| *n == repo || n.starts_with(&format!("{repo}/")))
                .map(|(_, d)| d.est_chunks)
                .sum::<u64>();
            suggestions.push(repo);
        }
    }
    let kept: Vec<String> = suggestions
        .iter()
        .filter(|s| {
            !suggestions
                .iter()
                .any(|o| o != *s && o.starts_with(&format!("{s}/")))
        })
        .cloned()
        .collect();
    let mut suggestions = kept;
    suggestions.sort();
    let mut ignored = walked.skipped_caches;
    ignored.sort();
    Report {
        total_files: dirs.values().map(|d| d.files).sum(),
        dirs,
        total_est_chunks: total,
        suggestions,
        suggested_savings: savings,
        ignored_caches: ignored,
    }
}
